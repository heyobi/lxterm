#!/bin/sh
# AlmaLinux's dnf libraries translated ahead of time, for the app (core/aot.c): a training
# run under LXRUN_PROF picks, in each library, the functions that hold 99% of its samples
# (tests/linux/prof_funcs.py, bounds from AlmaLinux's debuginfo); tools/aotgen.c turns their
# pages into C. The tables match a library by its build-id, so they fit the root that
# trained them (the almalinux:10 image the app downloads); another build of a library
# (a newer image, dnf upgrade) runs interpreted as before.
# Before OUT is written, lxrun is built with the tables and every check command must give
# the same output as without them.
# usage: sudo sh tools/aot-build.sh ROOT OUT      (an arm64 Linux host: debuginfo natively)
set -u
DIR="$(cd "$(dirname "$0")/.." && pwd)"
R=$(cd "$1" && pwd); OUT=$2
cd "$DIR" || exit 1
CORE=$(sed -n 's/^CORE *:= //p' Makefile)
mkdir -p build
make -s build/lxrun || exit 1
cc -O2 -Wall -o build/aotgen tools/aotgen.c || exit 1
cp /etc/resolv.conf "$R/etc/resolv.conf"
LXRUN_QUIET=1 build/lxrun "$R" /bin/bash -c 'dnf -y makecache' > /dev/null 2>&1   # (metadata for all runs)

echo "== training (interpreted, sampled)"
rm -rf build/prof build/ranges; mkdir -p build/prof
k=0
for cmd in 'dnf --version' 'dnf -C search nginx' 'dnf -C list --installed' 'dnf -y makecache' \
           'dnf -C repoquery --requires httpd' 'dnf -C info tmux' 'python3 -c "import hashlib, json; s=0
for i in range(200000): s+=i*i
print(hashlib.sha256(json.dumps([s]).encode()).hexdigest())"' 'rpm -qa' \
           'dnf -y -C --setopt=install_weak_deps=False install tmux; dnf -y -C remove tmux'; do
    k=$((k + 1))
    LXRUN_PROF=build/prof/$k.prof LXRUN_QUIET=1 timeout 1800 build/lxrun "$R" /bin/bash -c "$cmd" > /dev/null 2>&1
done
echo "== debug symbols (function bounds), natively"
mount -t proc proc "$R/proc"; mount --rbind /dev "$R/dev"
chroot "$R" /bin/bash -c "dnf -y -q --enablerepo='*-debuginfo' --setopt=strict=0 install python3-libs-debuginfo libsolv-debuginfo sqlite-libs-debuginfo rpm-libs-debuginfo rpm-sequoia-debuginfo libdnf-debuginfo libxml2-debuginfo glib2-debuginfo openssl-libs-debuginfo zlib-ng-compat-debuginfo bash-debuginfo glibc-debuginfo libcurl-debuginfo > /dev/null 2>&1"
umount -R "$R/dev" "$R/proc"
python3 tests/linux/prof_funcs.py "$R" 0.99 build/ranges build/prof/*.prof

echo "== translated"
LIBS="libsolv:usr/lib64/libsolv.so.1 libpython:usr/lib64/libpython3.12.so.1.0 libsqlite:usr/lib64/libsqlite3.so.0 librpm:usr/lib64/librpm.so.10 librpmio:usr/lib64/librpmio.so.10 libdnf:usr/lib64/libdnf.so.2 libxml2:usr/lib64/libxml2.so.2 libglib:usr/lib64/libglib-2.0.so.0 libcrypto:usr/lib64/libcrypto.so.3 libz:usr/lib64/libz.so.1 librpmseq:usr/lib64/librpm_sequoia.so.1 libsolvext:usr/lib64/libsolvext.so.1 bash:usr/bin/bash ldso:usr/lib/ld-linux-aarch64.so.1 libgcc:usr/lib64/libgcc_s.so.1 libcurl:usr/lib64/libcurl.so.4"
rm -rf build/aot; mkdir -p build/aot
TABLE="#include \"aot.h\"
"; REFS=""; total=0
for l in $LIBS; do
    name=${l%%:*}; real=$(readlink -f "$R/${l#*:}")
    rf="build/ranges/$(basename "$real").ranges"
    [ -s "$rf" ] || continue
    build/aotgen "$real" "$name" "build/aot/aot_$name.c" "$rf" || { rm -f "build/aot/aot_$name.c"; continue; }
    cc -O1 -g0 -w -std=gnu11 -Icore -DAOI_AOT -c "build/aot/aot_$name.c" -o "build/aot_$name.o" || { rm -f "build/aot/aot_$name.c"; continue; }
    sz=$(stat -c %s "build/aot_$name.o"); total=$((total + sz))
    TABLE="${TABLE}extern const struct aoi_aot_lib aot_$name;
"; REFS="$REFS &aot_$name,"
done
echo "   all translated code: $((total / 1024)) KiB of objects (this host)"
printf "/* Generated by tools/aot-build.sh (the app defines AOI_AOT when it carries these). */\n#ifdef AOI_AOT\n${TABLE}const struct aoi_aot_lib *const aoi_aot_libs[] = {$REFS 0 };\n#endif\n" > build/aot/aot_table.c
cc -O2 -g -std=c11 -Icore -DAOI_AOT -o build/lxrun-aot tools/lxrun.c $CORE build/aot_*.o build/aot/aot_table.c -lm -lpthread || { echo "link failed"; exit 1; }

bad=0
check() {   # check LABEL COMMAND: same output with the tables, and the time
    for b in lxrun lxrun-aot; do
        t0=$(date +%s.%N)
        LXRUN_STATS=1 LXRUN_QUIET=1 timeout 1800 build/$b "$R" /bin/bash -c "$2" > /tmp/out.$b 2> /tmp/err.$b
        echo "$(date +%s.%N) - $t0" | bc > /tmp/t.$b
    done
    sed -i -e 's/ *[0-9.]* [kM]B\/s.*//' -e '/^Last metadata expiration check/d' /tmp/out.lxrun /tmp/out.lxrun-aot
    if cmp -s /tmp/out.lxrun /tmp/out.lxrun-aot; then same=same; else same=DIFFERENT; bad=1; fi
    a=$(cat /tmp/t.lxrun); b=$(cat /tmp/t.lxrun-aot)
    printf '%-30s interpreted %7.2f s   translated %7.2f s   %4.0f%%   output %s\n' "$1" "$a" "$b" "$(echo "100 * (1 - $b / $a)" | bc -l)" "$same"
    [ $same = same ] || { diff /tmp/out.lxrun /tmp/out.lxrun-aot | head -n 10; tail -n 4 /tmp/err.lxrun-aot; }
}
echo "== checks"
check "dnf --version"             'dnf --version'
check "dnf -C search nginx"       'dnf -C search nginx'
check "dnf -C info httpd"         'dnf -C info httpd'
check "dnf -C list --available"   'dnf -C list --available | wc -l'
check "rpm -qa"                   'rpm -qa'
check "python3 json + re"         'python3 -c "import json, re; d=[{\"k\": i, \"v\": str(i)*5} for i in range(40000)]; s=json.dumps(d); print(len(s), len(re.findall(r\"[0-9]{5}\", s)), len(json.loads(s)))"'
check "dnf install tmux"          'dnf -y -C --setopt=install_weak_deps=False install tmux >/dev/null 2>&1; rpm -q tmux; dnf -y -C remove tmux >/dev/null 2>&1; rpm -q tmux'
[ $bad = 0 ] || { echo "outputs differ: no tables"; exit 1; }
rm -rf "$OUT"; mkdir -p "$OUT" && cp build/aot/*.c "$OUT/" && ls -l "$OUT"
